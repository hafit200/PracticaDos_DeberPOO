package modelo;

/**
 *
 * @author Asus
 */
public class Libros {
    private String titulo;
    private int id;
    private double precio;

    public Libros() {
    }

    public Libros(String titulo, int id, double precio) {
        this.titulo = titulo;
        this.id = id;
        this.precio = precio;
    }

    public String getTitulo() {
        return titulo;
    }

    public void setTitulo(String titulo) {
        this.titulo = titulo;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public double getPrecio() {
        return precio;
    }

    public void setPrecio(double precio) {
        this.precio = precio;
    }
    
    
}
